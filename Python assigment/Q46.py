# Write a program to import math module and compute trigonometric and logarithmic values
import math


angle = math.radians(45)   
number = 10

print("sin(45°):", math.sin(angle))
print("cos(45°):", math.cos(angle))
print("tan(45°):", math.tan(angle))

print("log base e of 10:", math.log(number))       
print("log base 10 of 10:", math.log10(number))    
print("log base 2 of 10:", math.log2(number))      